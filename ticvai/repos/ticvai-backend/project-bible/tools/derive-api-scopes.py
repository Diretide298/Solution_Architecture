#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Write `handoff/api-scopes.json`: the partner API scope catalogue `listApiScopes` serves.

**Why** (20 October 2026, r8 cause FOUNDATION-AI-C47, ticket 27981 SVC-PLATFORM-PUBLICAPI-7, CHG-R8GEN-008). The
contract says the catalogue "is generated at release from `x-ticvai-api-scope` on every partner-callable operation; it
is not edited by hand", and nothing generated it: the service had no runtime source for the scopes, so the ticket
could not be built. This is that generator. The service loads the file at startup (it changes only at a release);
`licensed` is not in the file, it is computed per request from the caller's tenant's `control.api_licence` rows.

One entry per scope, in the order the operation states: by module, then access (read before write), the scope string
as the tiebreak (which is also the cursor key):

    {"scope": "marketing.read", "module": "marketing", "access": "read", "description": "...",
     "operations": [{"contract": "marketing-crm", "operationId": "getGuestProfile"}, ...]}

A scope value that is not `<ModuleKey>.read` or `<ModuleKey>.write` is refused (the run fails), so a typo cannot
publish a scope no client can be granted.

    python tools/derive-api-scopes.py [--check]     (--check: compare with the file, write nothing)
"""
import glob
import io
import json
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "handoff", "api-scopes.json")
LOADER = getattr(yaml, "CSafeLoader", yaml.SafeLoader)
VERBS = ("get", "post", "put", "patch", "delete")
SCOPE = re.compile(r"^([a-zA-Z][a-zA-Z0-9]*)\.(read|write)$")


def module_keys():
    with io.open(os.path.join(ROOT, "contracts", "shared", "common.yaml"), encoding="utf-8") as fh:
        common = yaml.load(fh, Loader=LOADER) or {}
    return list(((common.get("components") or {}).get("schemas") or {}).get("ModuleKey", {}).get("enum") or [])


def catalogue():
    keys = module_keys()
    scopes, errors = {}, []
    for f in sorted(glob.glob(os.path.join(ROOT, "contracts", "*", "*.yaml"))):
        stem = os.path.basename(f)[:-5]
        with io.open(f, encoding="utf-8") as fh:
            doc = yaml.load(fh, Loader=LOADER) or {}
        for _p, item in (doc.get("paths") or {}).items():
            if not isinstance(item, dict):
                continue
            for v, op in item.items():
                if v not in VERBS or not isinstance(op, dict) or not op.get("operationId"):
                    continue
                s = op.get("x-ticvai-api-scope")
                if not s:
                    continue
                m = SCOPE.match(str(s))
                if not m or (keys and m.group(1) not in keys):
                    errors.append("%s.%s: x-ticvai-api-scope %r is not <ModuleKey>.read or <ModuleKey>.write"
                                  % (stem, op["operationId"], s))
                    continue
                e = scopes.setdefault(str(s), {"scope": str(s), "module": m.group(1), "access": m.group(2),
                                               "operations": []})
                e["operations"].append({"contract": stem, "operationId": op["operationId"]})
    out = []
    for s in sorted(scopes.values(), key=lambda e: (e["module"], e["access"] != "read", e["scope"])):
        s["operations"].sort(key=lambda o: (o["contract"], o["operationId"]))
        n = len(s["operations"])
        s["description"] = ("%s the %s module's partner operations (%d operation%s)"
                            % ("Reads" if s["access"] == "read" else "Writes through", s["module"], n,
                               "" if n == 1 else "s"))
        out.append({k: s[k] for k in ("scope", "module", "access", "description", "operations")})
    return out, errors


def render(scopes):
    doc = {
        "note": "Generated by tools/derive-api-scopes.py from x-ticvai-api-scope on every partner-callable operation. "
                "Do not edit. listApiScopes serves it (loaded at startup) in this order: module, then access (read "
                "before write), then scope; licensed is computed per request from control.api_licence.",
        "scopes": scopes,
    }
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    scopes, errors = catalogue()
    for e in errors:
        print("  FAIL  " + e)
    if errors:
        print("FAIL - %d scope value(s) no client can be granted" % len(errors))
        return 1
    text = render(scopes)
    old = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    print("  %d scope(s) over %d operation(s)" % (len(scopes), sum(len(s["operations"]) for s in scopes)))
    if "--check" in sys.argv:
        print("%s - handoff/api-scopes.json %s" % ("PASS" if old == text else "FAIL",
                                                 "is current" if old == text else "differs: run without --check"))
        return 0 if old == text else 1
    if old != text:
        with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print("  -> handoff/api-scopes.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
