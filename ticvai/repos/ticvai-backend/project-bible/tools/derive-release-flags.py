#!/usr/bin/env python3
"""The release-flag map: for each app-module of the plan, the screens it shows and the operations they bind.

    python3 tools/derive-release-flags.py            # writes handoff/release-flags.json
    python3 tools/derive-release-flags.py --check    # exits 1 when the file is not what this would write

**ADAM CR-164, decided 18 October 2026 (CHG-CRA-005).** PLATFORM-FLAGS keeps half-built features dark per tenant: a
flag's key is an app-module key of the plan (`AM-MARKETING-CRM-P01`) and covers that app-module's screens and the
operations they bind. The kernel needs the map from app-module to operations, and nothing in the package wrote it.
This writes it from the plan (`handoff/service-docs/tasks.csv`: each app-module feature's Builds, through
`tools/ticket_done.py` builds_of, the list ADAM indexes) and the screens (`screens/*.yaml` `apis`).

**The rule the backend applies** (the published answer): an operation is dark for a tenant only when **every**
app-module that binds it is off for that tenant, because many operations are bound by more than one app-module (the
answer counted 1,099 of 2,544 from the plan's Builds; with each screen's operations read too, the map holds 2,550, 1,388
of them shared), and the "any" rule would darken live modules. A flag the configuration does not declare counts as on.
`TenantAppStatus.darkAppModules` (white-label) tells the apps which modules are off.

ticvai-backend copies the file to `tools/release-flags/release-flags.json` and reads it from there; this one command
regenerates it after a plan or screen change.
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import ticket_done  # noqa: E402

OUT = ROOT / "handoff" / "release-flags.json"
NL, CR = chr(10), chr(13)


def screen_ops_of(folder: Path) -> dict:
    """screen id -> the operations its `apis` bind, from every `P*.yaml` in `folder`.

    **A screen file is `{platform, screens: [...]}`, not a list** (lane H review, 18 October 2026, C-1): the first
    version iterated the file's top-level keys, read no screen, and the map lost 668 module-to-operation bindings."""
    out: dict = {}
    for f in sorted(Path(folder).glob("P*.yaml")):
        doc = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        for s in (doc.get("screens") or []) if isinstance(doc, dict) else []:
            if isinstance(s, dict) and s.get("id"):
                out[s["id"]] = [a["operationId"] for a in s.get("apis") or []
                                if isinstance(a, dict) and a.get("operationId")]
    return out


def build() -> dict:
    lineage = json.loads((ROOT / "handoff" / "api-data-lineage.json").read_text(encoding="utf-8"))
    with (ROOT / "handoff" / "service-docs" / "tasks.csv").open(encoding="utf-8", newline="") as fh:
        rows = [r for r in csv.DictReader(fh) if "#" not in r["key"]]
    screen_ops = screen_ops_of(ROOT / "screens")

    def op_id(op):
        c = lineage.get(op, {}).get("contract")
        return f"{c}#{op}" if c else op

    modules = {}
    for r in rows:
        if r.get("type") != "Feature" or not r["key"].startswith("AM-"):
            continue
        screens, ops = set(), set()
        for b in ticket_done.builds_of(r, "", lineage):
            kind, _, name = b.partition(" ")
            if kind == "screen":
                screens.add(name)
                ops |= {op_id(o) for o in screen_ops.get(name, [])}
            elif kind == "operation":
                ops.add(name if "#" in name else op_id(name))
        if screens or ops:
            modules[r["key"]] = {"screens": sorted(screens), "operations": sorted(ops)}
    bound = collections.Counter(o for m in modules.values() for o in m["operations"])
    return {
        "_about": "Generated by tools/derive-release-flags.py from handoff/service-docs/tasks.csv and screens/*.yaml "
                  "(ADAM CR-164, CHG-CRA-005). Do not edit. An operation is dark for a tenant only when every "
                  "app-module that binds it is off for that tenant; a flag the configuration does not declare is on.",
        "rule": {"operationDarkWhen": "every binding app-module is off", "undeclaredFlag": "on"},
        "counts": {"appModules": len(modules), "operations": len(bound),
                   "sharedOperations": sum(1 for n in bound.values() if n > 1)},
        "appModules": dict(sorted(modules.items())),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = json.dumps(build(), indent=1, ensure_ascii=False) + NL
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8").replace(CR + NL, NL) != text:
            print("handoff/release-flags.json is not what tools/derive-release-flags.py writes: run it")
            return 1
        print("handoff/release-flags.json is current")
        return 0
    with OUT.open("w", encoding="utf-8", newline=NL) as fh:   # Python 3.9: no newline= on write_text
        fh.write(text)
    d = json.loads(text)
    print(f"  {d['counts']['appModules']} app-modules, {d['counts']['operations']} operations, "
          f"{d['counts']['sharedOperations']} bound by more than one -> handoff/release-flags.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
